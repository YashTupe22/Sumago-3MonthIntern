# Identity Operators
# 1. List Reference Comparison
a = [1, 2, 3]
b = a
c = [1, 2, 3]

print('List a: ', a)
print('List b: ', b)
print('List c: ', c)
print('a is b :- ', a is b)
print('a is c :- ', a is c)
print('a == c :- ', a == c)
# 2. Object Identity Checker
x = [10]
y = x
z = [10]

print('x is y :- ', x is y)
print('x is z :- ', x is z)
print('x == z :- ', x == z)

